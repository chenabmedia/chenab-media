export function getAllArtists(): Artist[] {
  return ARTISTS;
}

export function getArtistBySlug(slug: string): Artist | undefined {
  return ARTISTS.find((artist) => artist.slug === slug);
}

export function getArtistById(id: string): Artist | undefined {
  return ARTISTS.find((artist) => artist.id === id);
}

export function searchArtists(query: string, statusFilter: string = 'ALL'): Artist[] {
  const q = query.trim().toLowerCase();
  return ARTISTS.filter((artist) => {
    const matchesStatus =
      statusFilter === 'ALL' || artist.status.toUpperCase() === statusFilter.toUpperCase();

    if (!matchesStatus) return false;
    if (!q) return true;

    return (
      (artist.stageName || artist.name || '').toLowerCase().includes(q) ||
      artist.location.toLowerCase().includes(q) ||
      artist.genres.some((g) => g.toLowerCase().includes(q)) ||
      artist.bio.toLowerCase().includes(q)
    );
  });
}
